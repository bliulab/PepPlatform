def translate(message, language):
    if language != "zh":
        return message
    if message in ZH:
        return ZH[message]
    step = re.fullmatch(r"Step ([\d.]+): (.+)", message)
    if step:
        return f"第 {step[1]} 步：{translate(step[2], language)}"
    if message.startswith("Choose "):
        return translate(message[7:], language)
    for pattern, template in COMPILED:
        match = pattern.fullmatch(message)
        if match:
            return template.format(*(FAMILIES.get(value, value) for value in match.groups()))
    return message
